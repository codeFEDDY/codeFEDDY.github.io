async function copyCode(code) {
  if (!code) return false;
  try {
    await navigator.clipboard.writeText(code);
    showToast(`Copied ${code}`);
    return true;
  } catch (error) {
    showToast(`Use code ${code}`);
    return false;
  }
}

async function counterFetch(path) {
  const endpoints = [
    `https://api.countapi.xyz/${path}`,
    `https://countapi.xyz/${path}`
  ];

  for (const endpoint of endpoints) {
    try {
      const response = await fetch(endpoint, { cache: "no-store", mode: "cors" });
      if (!response.ok) continue;
      const data = await response.json();
      if (typeof data.value === "number") return data.value;
    } catch (error) {}
  }
  return null;
}

async function incrementCount(key, elementId, shouldIncrement = false) {
  const action = shouldIncrement ? "hit" : "get";
  const value = await counterFetch(`${action}/${TELEMETRY_NAMESPACE}/${key}`);
  const el = elementId ? document.getElementById(elementId) : null;
  if (el) el.textContent = value === null ? "—" : new Intl.NumberFormat().format(value);
  return value;
}

function companyMetricKey(vendor) {
  const v = String(vendor || "").toLowerCase();
  if (v.includes("revive")) return "revive";
  if (v.includes("delta")) return "delta";
  if (v.includes("cannaclear")) return "cannaclear";
  return "other";
}

function companyMetricElement(vendor) {
  const key = companyMetricKey(vendor);
  return {
    revive: "footerReviveClickCount",
    delta: "footerDeltaClickCount",
    cannaclear: "footerCannaClickCount"
  }[key] || null;
}

async function setupFooterTelemetry() {
  const visitKey = "codefeddy_visit_recorded_v42";
  const shouldHitVisit = !sessionStorage.getItem(visitKey);
  if (shouldHitVisit) sessionStorage.setItem(visitKey, "1");

  await incrementCount("visits", "footerVisitCount", shouldHitVisit);
  await incrementCount("offer-clicks", "footerClickCount", false);
  await incrementCount("code-copies", "footerCopyCount", false);
  await incrementCount("revive-clicks", "footerReviveClickCount", false);
  await incrementCount("delta-clicks", "footerDeltaClickCount", false);
  await incrementCount("cannaclear-clicks", "footerCannaClickCount", false);
}

function setupCodeLinks() {
  document.addEventListener("click", event => {
    const copyButton = event.target.closest(".copy-btn");
    if (copyButton) {
      event.preventDefault();
      copyCode(copyButton.dataset.code || "FEDDY");
      incrementCount("code-copies", "footerCopyCount", true);
      return;
    }

    const linkedOffer = event.target.closest(".js-offer-link, .open-link, .card-media, .quick-card");
    if (linkedOffer) {
      const code = linkedOffer.dataset.code || "FEDDY";
      const vendor = linkedOffer.dataset.vendor || "";

      // CannaClear does not reliably auto-apply from URL params. Tell users to type it manually instead.
      if (code && !String(vendor).toLowerCase().includes("cannaclear")) {
        copyCode(code);
      }

      incrementCount("offer-clicks", "footerClickCount", true);

      const companyKey = companyMetricKey(vendor);
      const companyElement = companyMetricElement(vendor);
      if (companyElement) incrementCount(`${companyKey}-clicks`, companyElement, true);
    }
  });
}

function setupBackground() {
  const video = $("#bgVideo");
  const gif = $("#bgGif");
  if (!video || !gif) return;
  video.muted = true;
  video.playsInline = true;
  video.addEventListener("canplay", () => {
    document.body.classList.remove("use-gif");
    video.play().catch(() => {});
  });
  video.addEventListener("error", () => document.body.classList.add("use-gif"));
  gif.addEventListener("error", () => document.body.classList.remove("use-gif"));
  window.setTimeout(() => {
    if (video.readyState >= 2) {
      document.body.classList.remove("use-gif");
      video.play().catch(() => {});
    }
  }, 700);
}






