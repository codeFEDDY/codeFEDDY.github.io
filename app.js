function showToast(message) {
  const toast = $("#toast");
  if (!toast) return;
  toast.textContent = message;
  toast.classList.add("show");
  window.clearTimeout(showToast._timer);
  showToast._timer = window.setTimeout(() => toast.classList.remove("show"), 1800);
}

function safeText(selector, value) {
  const el = $(selector);
  if (el) el.textContent = value;
}

function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function setupProofBlip() {
  safeText("#proofAccounts", "16");
  safeText("#proofReach", "3.3K");
  safeText("#proofLikes", "5.9K");
}

function compareDrops(a, b) {
  const vendorPriority = vendor => ({"Revive Hemp": 3, "Revive Hemp Store": 3, "The Delta Connect": 2, "CannaClear": 1}[vendor] || 0);
  if (state.sort === "name") return String(a.displayName || a.name || "").localeCompare(String(b.displayName || b.name || ""));
  if (state.sort === "code") return vendorPriority(b.vendor) - vendorPriority(a.vendor) || Number(Boolean(b.code)) - Number(Boolean(a.code)) || Number(b.featured || 0) - Number(a.featured || 0);
  if (state.sort === "rebate") return vendorPriority(b.vendor) - vendorPriority(a.vendor) || (String(b.type || "").toLowerCase().includes("rebate") - String(a.type || "").toLowerCase().includes("rebate"));
  return vendorPriority(b.vendor) - vendorPriority(a.vendor) || Number(b.featured || 0) - Number(a.featured || 0);
}

function filteredDrops() {
  const q = state.query.trim().toLowerCase();
  return state.drops
    .filter(drop => {
      const haystack = [drop.displayName, drop.name, drop.vendor, drop.category, drop.type, drop.description, ...(drop.tags || [])].join(" ").toLowerCase();
      const categoryOk = state.category === "all" || haystack.includes(state.category);
      const queryOk = !q || haystack.includes(q);
      return categoryOk && queryOk;
    })
    .sort(compareDrops);
}

